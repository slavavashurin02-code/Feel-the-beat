//  Как писать комбинацию (поле timings):
//    Числа идут по очереди: вибрация, пауза, вибрация, пауза, ... — всё в миллисекундах.
//    Первое число — всегда вибрация.
//    Пример: [200, 100, 200, 100, 400]
//      200 мс вибрация, 100 мс пауза, 200 мс вибрация, 100 мс пауза, 400 мс вибрация.
//
//  Если нужна разная сила ударов (только в приложении) — добавьте поле amplitudes:
//    это второй список ТОЙ ЖЕ длины, что и timings. Для каждого шага — сила:
//    0 = пауза, от 1 до 255 = вибрация (255 — максимум).
//    Пример:
//      timings:    [200, 100, 200, 100, 400]
//      amplitudes: [255,   0, 128,   0,  60]
//    Если amplitudes не писать (оставить null), все вибрации будут на полную силу.
//
//  Название (title) — это текст на кнопке, его можно менять как угодно.
//  Пока список timings пустой, кнопка показывает, что место свободно.
